create or replace function wow_fin.can(ctx jsonb,cap text) returns boolean language sql immutable set search_path='' as $$
 select ctx->'account'->>'role'='owner' or ((ctx->'account'->'permissions') ? cap and
 (ctx->'account'->'permissions') ? (split_part(cap,'.',1)||'.view')) $$;
create or replace function wow_fin.derived(seed text) returns uuid language sql immutable set search_path='' as $$
 select overlay(overlay(md5(seed) placing '5' from 13 for 1) placing '8' from 17 for 1)::uuid $$;
create or replace function wow_fin.num(v text) returns numeric language sql immutable set search_path='' as $$
 select case when v ~ '^-?[0-9]{1,16}([.][0-9]{1,16})?$' then v::numeric end $$;
create or replace function wow_fin.day(v text) returns date language plpgsql immutable set search_path='' as $$
begin
 if left(v,10) ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' then return left(v,10)::date;end if;return null;
exception when datetime_field_overflow or invalid_datetime_format then return null;
end $$;

create or replace view wow_fin.boxes as
select w.id workspace,'main:'||c id,c currency,jsonb_build_object('name',c,'currency',c,'active',true,'threshold','0','system',true) profile,0 version
from public.wow_workspaces w cross join unnest(array['USD','TRY','EUR','SYP']) c
union all select workspace,id::text,profile->>'currency',profile,version from wow_fin.resources where kind='box';

-- Toplevel cash receipts win over historical invoice snapshots, just as in WOWStatementCore.collectPayments.
create or replace view wow_fin.payment_records as
with candidates as (
 select r.workspace_id workspace,r.record_id::text origin,r.payload p,0 priority,0::bigint ord
 from public.wow_records r where r.store='payments' and r.deleted_at is null
 union all
 select r.workspace_id,r.record_id::text,p.value||jsonb_build_object('invoiceId',coalesce(nullif(p.value->'invoiceId','null'),r.record_id)),1,p.ordinality
 from public.wow_records r cross join lateral jsonb_array_elements(case when jsonb_typeof(r.payload->'payments')='array' then r.payload->'payments' else '[]'::jsonb end)
 with ordinality p(value,ordinality) where r.store='invoices' and r.deleted_at is null and jsonb_typeof(p.value)='object'
), eligible as (
 select c.*,coalesce('id:'||nullif(p->>'id',''),'snapshot:'||origin||':'||ord) as key from candidates c
 where coalesce(p->>'deleted','false')<>'true' and coalesce(p->>'isDeleted','false')<>'true' and coalesce(p->>'voided','false')<>'true'
)
select distinct on(workspace,key) workspace,key,p from eligible order by workspace,key,priority,origin,ord;

create or replace view wow_fin.cash as
select l.workspace,l.entry::text entry,j.scope,j.kind,j.day,l.box,l.currency,l.amount,j.detail,j.reversed_entry::text reversed_entry
from wow_fin.legs l join wow_fin.journal j on j.workspace=l.workspace and j.id=l.entry
union all
select r.workspace_id,r.record_id#>>'{}','wow',coalesce(r.payload->>'type','movement'),wow_fin.day(r.payload->>'date'),
 'main:'||(t->>'currency'),t->>'currency',round(wow_fin.num(t->>'units')/100,2),
 jsonb_build_object('description',r.payload->>'note','reference',r.record_id),null
from public.wow_records r cross join lateral jsonb_array_elements(case when jsonb_typeof(r.payload->'legs')='array' then r.payload->'legs' else '[]'::jsonb end) t
where r.store='settings' and r.deleted_at is null and (r.record_id#>>'{}') like 'cashbox-entry/%'
 and (r.record_id#>>'{}') not like 'cashbox-entry/finance/%' and (t->>'units') ~ '^-?[0-9]{1,15}$' and (t->>'currency') in ('TRY','USD','EUR','SYP')
union all
select p.workspace,p.key,'wow','invoice',wow_fin.day(coalesce(p.p->>'date',p.p->>'paymentDate',p.p->>'createdAt')),
 'main:'||a.cur,a.cur,round(a.amount,2),jsonb_build_object('description',p.p->>'note','reference',p.p->'invoiceId',
 'party',case when c.record_id is not null then jsonb_build_object('type','customer','id',c.record_id) end),null
from wow_fin.payment_records p
left join public.wow_records i on i.workspace_id=p.workspace and i.store='invoices' and i.record_id=p.p->'invoiceId' and i.deleted_at is null
left join public.wow_records c on c.workspace_id=p.workspace and c.store='companies' and c.record_id=coalesce(i.payload->'companyId',p.p->'companyId',p.p->'customerId') and c.deleted_at is null
cross join lateral(
 select case when p.p->>'originalAmount' is not null and coalesce(p.p->>'originalCurrency','')<>'' then p.p->>'originalCurrency'
   when p.p->>'amountBasis'='USD' then 'USD' else p.p->>'currency' end currency,
 wow_fin.num(case when p.p->>'originalAmount' is not null and coalesce(p.p->>'originalCurrency','')<>'' then p.p->>'originalAmount' else p.p->>'amount' end) amount
) o cross join lateral (select case when upper(o.currency)='TL' then 'TRY' else upper(o.currency) end cur,o.amount) a
where p.p->>'receiptType'='cash' and a.amount is not null and a.cur in ('TRY','USD','EUR','SYP');

create or replace function wow_fin.box_currency(w uuid,b text) returns text language plpgsql stable set search_path='' as $$
declare cur text;
begin select currency into cur from wow_fin.boxes where workspace=w and id=b and coalesce((profile->>'active')::boolean,false);
 if cur is null then raise exception using message='INVALID_CASHBOX';end if;return cur;
end $$;
create or replace function wow_fin.balance(w uuid,b text) returns numeric language sql stable set search_path='' as $$
 select round(coalesce(sum(amount),0),2) from wow_fin.cash where workspace=w and box=b $$;

-- Generic WOW sync and the native finance module share one cash projection.
-- Keep historical owner bootstrap/restore distinct from a new live withdrawal.
create or replace function wow_fin.sync_cash_snapshot(w uuid) returns jsonb
language sql stable set search_path='' as $$
 select coalesce(jsonb_object_agg(b.box,b.balance::text),'{}'::jsonb) from
  (select c.box,round(sum(c.amount),2) balance from wow_fin.cash c where c.workspace=w group by c.box) b
$$;
create or replace function wow_fin.sync_cash_validate(w uuid,previous jsonb) returns void
language plpgsql set search_path='' as $$
begin
 if exists(select 1 from wow_fin.cash c where c.workspace=w group by c.box
  having round(sum(c.amount),2)<least(0,coalesce((previous->>c.box)::numeric,0))) then
  raise exception using message='INVALID_INSUFFICIENT_BALANCE',errcode='P0001';
 end if;
end $$;

-- The primary WOW Cashboxes page reads this append-only representation. No private payroll or counterparty metadata leaves this schema.
create or replace function wow_fin.cash_mirror(w uuid,e uuid) returns jsonb language sql stable set search_path='' as $$
 select jsonb_build_object('id','cashbox-entry/finance/'||j.id::text,'date',j.day,
    'type',case when count(*)=2 then 'transfer' when sum(l.amount)<0 then 'expense' when j.kind='opening' then 'opening' else 'receipt' end,
    'note',case when j.scope='finance' then coalesce(j.detail->>'description',j.detail->>'reference',j.kind) else j.scope end,
    'legs',jsonb_agg(jsonb_build_object('currency',l.currency,'units',round(l.amount*100))
                     order by (l.amount<0) desc,l.box))
 from wow_fin.journal j join wow_fin.legs l on l.workspace=j.workspace and l.entry=j.id
 where j.workspace=w and j.id=e group by j.workspace,j.id
$$;

-- The shared worker receives amounts from the committed cash legs. Employee,
-- payroll, counterparty, commodity and document data stay in the private module.
create or replace function wow_fin.notice_text(v text,cap integer) returns text language sql immutable set search_path='' as $$
 select nullif(left(btrim(translate(regexp_replace(v,'[[:cntrl:]]','','g'),U&'\202A\202B\202C\202D\202E\2066\2067\2068\2069','')),cap),'')
$$;
create or replace function wow_fin.enqueue_cash(w uuid,u uuid,e uuid,mirror jsonb) returns void language plpgsql set search_path='' as $$
declare
 entry wow_fin.journal; debit jsonb=mirror->'legs'->0; credit jsonb=mirror->'legs'->1;
 event_kind text; event_action text='created'; movement text=mirror->>'type'; payload jsonb; previous wow_fin.legs;
begin
 select * into strict entry from wow_fin.journal where workspace=w and id=e;
 -- Only the server restore transaction sets importing. Requests cannot suppress their own live postings.
 if current_setting('wow_fin.importing',true)='yes' or entry.kind='opening' or
    (entry.reversed_entry is not null and (current_setting('wow_fin.correcting',true)=entry.reversed_entry::text or
       exists(select from wow_fin.journal orig where orig.workspace=w and orig.id=entry.reversed_entry and orig.kind='opening'))) then return;end if;
 event_kind=case movement when 'transfer' then 'expense' else movement end;
 payload=jsonb_build_object('movement',movement,'date',entry.day,'amount',abs((debit->>'units')::numeric)/100,'currency',debit->>'currency');
 if credit is not null then
  payload=payload||jsonb_build_object('receivedAmount',abs((credit->>'units')::numeric)/100,'receivedCurrency',credit->>'currency');
 end if;
 if entry.scope='finance' then
  payload=payload||jsonb_strip_nulls(jsonb_build_object(
   'reference',wow_fin.notice_text(entry.detail->>'reference',80),
   'note',wow_fin.notice_text(coalesce(nullif(entry.detail->>'note',''),entry.detail->>'description'),180),
   'actorName',wow_fin.notice_text((select a.name from public.wow_accounts a where a.id=u and a.workspace_id=w),80)));
  if entry.kind in ('income','expense') and entry.detail->>'replaces' is not null then
   event_action='updated';
   select * into strict previous from wow_fin.legs l where l.workspace=w and l.entry=(entry.detail->>'replaces')::uuid;
   payload=payload||jsonb_build_object('previousAmount',abs(previous.amount),'previousCurrency',previous.currency);
  end if;
 end if;
 perform public.wow_push_enqueue(w,u,jsonb_build_array(jsonb_build_object(
   'store','settings','id',mirror->'id','revision',1,'kind',event_kind,'action',event_action,'details',payload)),'live');
end $$;

create or replace function wow_fin.guard_mirror() returns trigger language plpgsql set search_path='' as $$
declare generated boolean;
begin
 if tg_op in ('UPDATE','DELETE') and old.store='settings' and (old.record_id#>>'{}') like 'cashbox-entry/finance/%' then
  raise exception using message='ACCESS_DENIED';end if;
 if tg_op='DELETE' then return old;end if;
 generated=new.store='settings' and (new.record_id#>>'{}') like 'cashbox-entry/finance/%';
 if generated and (tg_op<>'INSERT' or new.revision<>1 or new.deleted_at is not null or not exists(
  select from wow_fin.journal j where j.workspace=new.workspace_id and j.actor=new.updated_by
   and ('cashbox-entry/finance/'||j.id::text)=(new.record_id#>>'{}') and new.payload=wow_fin.cash_mirror(j.workspace,j.id))) then raise exception using message='ACCESS_DENIED';end if;
 return new;
end $$;
drop trigger if exists wow_fin_mirror on public.wow_records;
create trigger wow_fin_mirror before insert or update or delete on public.wow_records for each row execute function wow_fin.guard_mirror();

create or replace function wow_fin.post(w uuid,u uuid,eid uuid,s text,k text,d date,info jsonb,postings jsonb,
 commodity text default null,weight numeric default 0,original uuid default null) returns uuid
language plpgsql set search_path='' as $$
declare leg jsonb;cur text;val numeric;mirror jsonb;rid jsonb;change_id bigint;
begin
 if eid is null or d is null or jsonb_array_length(postings) not between 1 and 2 then raise exception using message='INVALID_POSTING';end if;
 if commodity is not null and coalesce((select sum(grams) from wow_fin.journal where workspace=w and metal=commodity),0)+weight<0 then
  raise exception using message='INVALID_METAL_HOLDINGS';end if;
 insert into wow_fin.journal(workspace,id,scope,kind,day,detail,actor,reversed_entry,metal,grams) values(w,eid,s,k,d,info,u,original,commodity,weight);
 for leg in select value from jsonb_array_elements(postings) loop
  if original is null then cur=wow_fin.box_currency(w,leg->>'box');
  else select b.currency into cur from wow_fin.boxes b where b.workspace=w and b.id=leg->>'box';end if;
  val=wow_fin.num(leg->>'amount');
  if cur is null or val is null or val=0 or val<>round(val,2) or abs(val)>999999999999.99 then raise exception using message='INVALID_POSTING';end if;
  if val<0 and (original is null or coalesce(current_setting('wow_fin.correcting',true),'')<>original::text) and wow_fin.balance(w,leg->>'box')+val<0 then raise exception using message='INVALID_INSUFFICIENT_BALANCE';end if;
  insert into wow_fin.legs values(w,eid,leg->>'box',cur,val);
 end loop;
 rid=to_jsonb('cashbox-entry/finance/'||eid::text);
 mirror=wow_fin.cash_mirror(w,eid);
 insert into public.wow_records(workspace_id,store,record_id,payload,revision,updated_by)
 values(w,'settings',rid,mirror,1,u) returning wow_records.change_id into change_id;
 update public.wow_workspaces set data_revision=change_id where id=w;
 perform wow_fin.enqueue_cash(w,u,eid,mirror);
 return eid;
end $$;

create or replace function wow_fin.reverse_entry(w uuid,u uuid,eid uuid,orig uuid,s text,d date,reason text) returns uuid language plpgsql set search_path='' as $$
declare j wow_fin.journal;legs jsonb;
begin
 select * into j from wow_fin.journal where workspace=w and id=orig and scope=s;
 if j.id is null or j.reversed_entry is not null or exists(select from wow_fin.journal where workspace=w and reversed_entry=orig) or d<j.day then
  raise exception using message='INVALID_REVERSAL';end if;
 if j.kind='metalOpening' then
  if coalesce((select sum(grams) from wow_fin.journal where workspace=w and metal=j.metal),0)-j.grams<0 then raise exception using message='INVALID_METAL_HOLDINGS';end if;
  insert into wow_fin.journal(workspace,id,scope,kind,day,detail,actor,reversed_entry,metal,grams)
  values(w,eid,s,'reversal',d,j.detail||jsonb_build_object('reason',reason,'originalKind',j.kind),u,orig,j.metal,-j.grams);return eid;end if;
 select jsonb_agg(jsonb_build_object('box',l.box,'amount',(-l.amount)::text) order by l.box) into legs from wow_fin.legs l where l.workspace=w and l.entry=orig;
 perform wow_fin.post(w,u,eid,s,'reversal',d,j.detail||jsonb_build_object('reason',reason,'originalKind',j.kind),legs,j.metal,-j.grams,orig);
 if j.scope='payroll' and j.kind='salary' and not exists(select from wow_fin.journal payout where payout.workspace=w and payout.kind='salary' and
   payout.detail->>'employee'=j.detail->>'employee' and payout.detail->>'period'=j.detail->>'period' and not exists(select from wow_fin.journal undo where undo.workspace=w and undo.reversed_entry=payout.id)) then
  update wow_fin.slips set active=false where workspace=w and employee=(j.detail->>'employee')::uuid and period=((j.detail->>'period')||'-01')::date and active;
 end if;
 return eid;
end $$;

create or replace function wow_fin.salary(w uuid,emp uuid,p date) returns jsonb language plpgsql stable set search_path='' as $$
declare profile jsonb; paid jsonb; model text;rate numeric; shifts numeric=0;hrs numeric=0; additions numeric=0;deductions numeric=0;
 advances numeric=0;base numeric;breakdown jsonb;settled numeric;last_payment uuid;
begin
 select s.details||jsonb_build_object('paid',true,'payment',s.entry) into paid from wow_fin.slips s where s.workspace=w and s.employee=emp and s.period=p and s.active;
 if paid is not null then
  select coalesce(-sum(l.amount),0),(array_agg(j.id order by j.created_at desc,j.id desc))[1] into settled,last_payment from wow_fin.journal j
  join wow_fin.legs l on l.workspace=j.workspace and l.entry=j.id where j.workspace=w and j.kind='salary' and j.detail->>'employee'=emp::text and j.detail->>'period'=to_char(p,'YYYY-MM')
  and not exists(select from wow_fin.journal undo where undo.workspace=w and undo.reversed_entry=j.id);
  return paid||jsonb_build_object('frozen',true,'paid',settled>=(paid->>'net')::numeric,'paidAmount',settled::text,'remaining',greatest(0,(paid->>'net')::numeric-settled)::text,'payment',last_payment);
 end if;
 select r.profile into profile from wow_fin.resources r where r.workspace=w and r.kind='employee' and r.id=emp;
 if profile is null then raise exception using message='INVALID_EMPLOYEE';end if;
 model=profile->>'model';rate=(profile->>'rate')::numeric;
 select coalesce(sum(case when kind in ('present','late') then 1 when kind='half' then 0.5 else 0 end),0),
  coalesce(sum((entry->>'hours')::numeric) filter(where kind in ('present','late','half')),0),
  coalesce(sum((entry->>'value')::numeric) filter(where kind in ('piece','overtime','bonus')),0),
  coalesce(sum((entry->>'value')::numeric) filter(where kind in ('absent','half','late','deduction')),0),
  coalesce(sum((entry->>'value')::numeric) filter(where kind='advance'),0)
 into shifts,hrs,additions,deductions,advances from wow_fin.attendance a
 where a.workspace=w and a.employee=emp and a.active and a.day>=p and a.day<p+interval '1 month';
 select coalesce(jsonb_object_agg(b.kind,jsonb_build_object('count',b.n,'amount',b.total::text,'hours',b.hours::text,'quantity',b.qty::text)),'{}') into breakdown
 from (select a.kind,count(*) n,sum((entry->>'value')::numeric) total,sum((entry->>'hours')::numeric) hours,sum((entry->>'quantity')::numeric) qty
  from wow_fin.attendance a where a.workspace=w and a.employee=emp and a.active and a.day>=p and a.day<p+interval '1 month' group by a.kind) b;
 base=round(case model when 'monthly' then rate when 'daily' then rate*shifts when 'hourly' then rate*hrs else 0 end,2);
 return jsonb_build_object('employee',emp,'name',profile->>'name','model',model,'currency',profile->>'currency','box',profile->'box',
 'period',to_char(p,'YYYY-MM'),'eligible',coalesce((profile->>'active')::boolean,false) and profile->>'status'='active' and
  (profile->>'start' is null or (profile->>'start')::date<p+interval '1 month'),
 'base',base::text,'additions',additions::text,'deductions',deductions::text,'advances',advances::text,
 'net',greatest(0,base+additions-deductions-advances)::text,'shortfall',greatest(0,deductions+advances-base-additions)::text,
 'days',shifts::text,'hours',hrs::text,'breakdown',breakdown,'paid',false,'frozen',false,'paidAmount','0.00','remaining',greatest(0,base+additions-deductions-advances)::text);
end $$;

create or replace function wow_fin.attend(w uuid,u uuid,command uuid,r jsonb,remove_row boolean default false) returns void language plpgsql set search_path='' as $$
declare key uuid=(r->>'id')::uuid;old wow_fin.attendance;emp uuid;d date;k text;prof jsonb;val numeric=0;nominal numeric;
 hrs numeric;late numeric;qty numeric;rate numeric;cash text;advance uuid;shift boolean;
begin
 select * into old from wow_fin.attendance a where a.workspace=w and a.id=key;
 if coalesce(old.version,0)<>(r->>'version')::int or old.active=false or (remove_row and old.id is null) then raise exception using message='CONFLICT';end if;
 if remove_row then emp=old.employee;d=old.day;k=old.kind;
 else emp=(r->>'employee')::uuid;d=(r->>'day')::date;k=r->>'kind';end if;
 if old.id is not null and (old.employee<>emp or old.day<>d) then raise exception using message='INVALID_ATTENDANCE';end if;
 if exists(select from wow_fin.slips s where s.workspace=w and s.employee=emp and s.period=date_trunc('month',d)::date and s.active) then
  raise exception using message='INVALID_PAID_PERIOD';end if;
 if old.advance_entry is not null then
  perform wow_fin.reverse_entry(w,u,wow_fin.derived(command::text||key::text||'undo'),old.advance_entry,'payroll',d,'Attendance correction');end if;
 if remove_row then update wow_fin.attendance set active=false,version=version+1,advance_entry=null where workspace=w and id=key;return;end if;
 select profile into prof from wow_fin.resources where workspace=w and kind='employee' and id=emp;
 if prof is null or not (prof->>'active')::boolean or (prof->>'start' is not null and d<(prof->>'start')::date) then raise exception using message='INVALID_EMPLOYEE';end if;
 shift=k in ('present','half','absent','late');
 if shift and exists(select from wow_fin.attendance a where a.workspace=w and a.employee=emp and a.day=d and a.active and a.id<>key and a.kind in ('present','late','half','absent')) then
  raise exception using message='CONFLICT';end if;
 hrs=(r->>'hours')::numeric;late=(r->>'lateHours')::numeric;qty=(r->>'quantity')::numeric;rate=(prof->>'rate')::numeric;
 if hrs>24 or late>24 or (k='late' and late<=0) or (k='overtime' and hrs<=0) or (k='piece' and qty<=0) then raise exception using message='INVALID_ATTENDANCE';end if;
 if k in ('present','late','half') and hrs=0 then hrs=(prof->>'hours')::numeric*(case when k='half' then 0.5 else 1 end);end if;
 nominal=case prof->>'model' when 'monthly' then rate/(prof->>'days')::numeric/(prof->>'hours')::numeric when 'daily' then rate/(prof->>'hours')::numeric when 'hourly' then rate end;
 val=case k when 'absent' then case when prof->>'model'='monthly' then (prof->>'absence')::numeric else 0 end
  when 'half' then case when prof->>'model'='monthly' then rate/(prof->>'days')::numeric/2 else 0 end
  when 'late' then late*(prof->>'lateRate')::numeric
  when 'overtime' then hrs*coalesce(nullif((prof->>'overtimeRate')::numeric,0),nominal*(prof->>'multiplier')::numeric)
  when 'piece' then qty*coalesce((r->>'unit')::numeric,case when prof->>'model'='piece' then rate end)
  when 'bonus' then (r->>'amount')::numeric when 'deduction' then (r->>'amount')::numeric when 'advance' then (r->>'amount')::numeric else 0 end;
 val=round(val,2);
 if val is null or val<0 or (k in ('overtime','piece','bonus','advance','deduction') and val<=0) then raise exception using message='INVALID_ATTENDANCE';end if;
 if k='advance' then
  cash=coalesce(r->>'box',prof->>'box');
  if wow_fin.box_currency(w,cash)<>prof->>'currency' then raise exception using message='INVALID_CURRENCY';end if;
  advance=wow_fin.derived(command::text||key::text||'advance');
  perform wow_fin.post(w,u,advance,'payroll','advance',d,jsonb_build_object('employee',emp,'attendance',key),
    jsonb_build_array(jsonb_build_object('box',cash,'amount',-val)));
 end if;
 insert into wow_fin.attendance(workspace,id,employee,day,kind,version,entry,advance_entry) values(w,key,emp,d,k,coalesce(old.version,0)+1,
 r||jsonb_build_object('value',val::text,'hours',hrs::text,'currency',prof->>'currency'),advance)
 on conflict(workspace,id) do update set kind=excluded.kind,version=excluded.version,entry=excluded.entry,advance_entry=excluded.advance_entry;
end $$;

create or replace function wow_fin.payment_usd(p jsonb,i jsonb) returns numeric language sql immutable set search_path='' as $$
 select round(coalesce(wow_fin.num(p->>'amountUSD'),case when p->>'amountBasis'='USD' or coalesce(p->>'currency','USD')='USD' then wow_fin.num(p->>'amount')
 else wow_fin.num(p->>'amount')/nullif(coalesce(wow_fin.num(p->>k),wow_fin.num(p->'rates'->>k),wow_fin.num(i->>k),wow_fin.num(i->'rates'->>k)),0) end),2)
 from (select case upper(p->>'currency') when 'TL' then 'usdTry' when 'TRY' then 'usdTry' when 'EUR' then 'usdEur' when 'SYP' then 'usdSyp' end k) key $$;

create or replace function wow_fin.query_rows(w uuid,ctx jsonb,s text,b jsonb) returns setof jsonb language plpgsql stable set search_path='' as $$
declare tab text=b->>'tab';start_day date=(b->>'from')::date;end_day date=(b->>'to')::date;month_day date=coalesce(((b->>'period')||'-01')::date,date_trunc('month',current_date)::date);
 page_size integer=greatest(1,least(200,coalesce((b->>'limit')::int,50)))+1; page_start integer=greatest(0,coalesce((b->>'offset')::int,0));
begin
 if tab='boxes' then
  return query select x.profile||jsonb_build_object('id',x.id,'version',x.version,'balance',case when wow_fin.can(ctx,'finance.view') then coalesce(bal.balance,0)::text end)
   from wow_fin.boxes x left join(select c.box,round(sum(c.amount),2) balance from wow_fin.cash c where c.workspace=w and wow_fin.can(ctx,'finance.view') group by c.box) bal on bal.box=x.id
   where x.workspace=w order by x.currency,x.id limit page_size offset page_start;
 elsif tab='legacy' then
  if ctx->'account'->>'role'<>'owner' then raise exception using message='ACCESS_DENIED';end if;
  return query select jsonb_build_object('id',h.id,'version',h.version,'table',h.family,'sourceId',h.source_id,'name',coalesce(h.record->>'name',h.record->>'description',h.record->>'invoice_number',h.record->>'name_tr',h.record->>'metal_type'),
    'day',h.record->>'date','target',h.target) from wow_fin.legacy_rows h
   where h.workspace=w and h.scope=s and (b->>'legacyTable' is null or h.family=b->>'legacyTable')
   and position(lower(coalesce(b->>'search','')) in lower(h.record::text||' '||h.source_id::text))>0 order by h.family,h.source_id,h.id limit page_size offset page_start;
 elsif tab='barcodes' then
