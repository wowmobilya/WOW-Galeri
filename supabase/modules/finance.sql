create index if not exists wow_fin_box_legs on wow_fin.legs(workspace,box);
create table if not exists wow_fin.quotes(
 workspace uuid not null references public.wow_workspaces(id), id uuid not null,base text not null,counter text not null,
 rate numeric(28,8) not null check(rate>0),observed timestamptz not null,recorded timestamptz not null default now(),
 source text not null,method text not null,unit text not null,raw numeric(28,8) not null check(raw>0),primary key(workspace,id));
create index if not exists wow_fin_quotes_pair on wow_fin.quotes(workspace,base,counter,observed desc);
create table if not exists wow_fin.attendance(
 workspace uuid not null references public.wow_workspaces(id),id uuid not null, employee uuid not null, day date not null,kind text not null,
 version int not null,entry jsonb not null,active boolean not null default true,advance_entry uuid,primary key(workspace,id),
 foreign key(workspace,advance_entry) references wow_fin.journal(workspace,id));
create unique index if not exists wow_fin_shift on wow_fin.attendance(workspace,employee,day)
 where active and kind in ('present','absent','half','late');
create index if not exists wow_fin_att_month on wow_fin.attendance(workspace,employee,day) where active;
create table if not exists wow_fin.slips(
 workspace uuid not null,employee uuid not null,period date not null,entry uuid not null,details jsonb not null,active boolean not null default true,
 primary key(workspace,entry),foreign key(workspace,entry) references wow_fin.journal(workspace,id));
create unique index if not exists wow_fin_one_payment on wow_fin.slips(workspace,employee,period) where active;
create table if not exists wow_fin.receipts(
 seq bigint generated by default as identity, workspace uuid not null references public.wow_workspaces(id),
 id uuid not null,scope text not null,action text not null,request jsonb not null,result jsonb not null,actor uuid not null references public.wow_accounts(id),
 at timestamptz not null default now(),primary key(workspace,id),unique(seq));
create index if not exists wow_fin_receipts_scope on wow_fin.receipts(workspace,scope,seq);
create table if not exists wow_fin.attachments(
 workspace uuid not null references public.wow_workspaces(id),id uuid not null,scope text not null, name text not null,mime text not null,
