   and position(lower(coalesce(b->>'search','')) in lower(r.profile::text))>0 order by r.profile->>'name',r.id limit page_size offset page_start;
 elsif tab='resources' then
  return query select r.profile||jsonb_build_object('id',r.id,'kind',r.kind,'version',r.version) from wow_fin.resources r where r.workspace=w and
  ((s='payroll' and r.kind='employee') or (s='finance' and r.kind in ('box','category','vendor'))) and (b->>'resource' is null or r.kind=b->>'resource')
  and position(lower(coalesce(b->>'search','')) in lower(r.profile::text))>0 order by r.kind,r.profile->>'name',r.id limit page_size offset page_start;
 elsif tab='customers' then
  if not wow_fin.can(ctx,'customers.view') then raise exception using message='ACCESS_DENIED';end if;
  return query select jsonb_build_object('id',r.record_id,'name',r.payload->>'name','phone',r.payload->>'phone','company',r.payload->>'company') from public.wow_records r
   where r.workspace_id=w and r.store='companies' and r.deleted_at is null and position(lower(coalesce(b->>'search','')) in lower(coalesce(r.payload->>'name','')))>0 order by r.payload->>'name',r.record_id limit page_size offset page_start;
 elsif tab='invoices' then
  if not wow_fin.can(ctx,'invoices.view') or not wow_fin.can(ctx,'payments.view') then raise exception using message='ACCESS_DENIED';end if;
  return query select jsonb_build_object('id',r.record_id,'reference',r.payload->>'invNo','customer',r.payload->>'companyName','companyId',r.payload->'companyId',
   'day',wow_fin.day(coalesce(r.payload->>'regDate',r.payload->>'date',r.payload->>'createdAt')),'due',d.due,'currency','USD','total',t.total::text,
   'paid',case when not p.unknown then f.paid::text end,'remaining',case when not p.unknown then (t.total-f.paid)::text end,
   'status',case when r.payload->>'deleted'='true' or r.payload->>'isDeleted'='true' or r.payload->>'voided'='true' or r.payload->>'cancelled'='true' or r.payload->>'canceled'='true' then 'void'
   when lower(r.payload->>'status') in ('cancelled','canceled','draft','void') then r.payload->>'status'
   when p.unknown or t.total is null then 'review' when f.paid>=t.total then 'paid' when d.due<current_date then 'overdue' else 'pending' end)
  from public.wow_records r cross join lateral(select wow_fin.num(coalesce(r.payload->>'grandTotal',r.payload->>'grandTotalUSD')) total,
   coalesce(wow_fin.num(coalesce(r.payload->>'depositUSD',r.payload->>'deposit')),0) deposit) t
  cross join lateral(select coalesce(wow_fin.day(r.payload->>'paymentDueDate'),wow_fin.day(r.payload->>'dueDate')) due) d
  cross join lateral(select coalesce(sum(z.usd),0) paid,coalesce(sum(z.usd) filter(where z.deposit),0) deposited,count(*) filter(where z.usd is null)>0 unknown
   from (select wow_fin.payment_usd(q.p,r.payload) usd,(q.p->>'isDeposit'='true' or q.p->>'kind'='deposit' or q.p->>'type'='deposit') deposit
   from wow_fin.payment_records q where q.workspace=w and q.p->'invoiceId'=r.record_id) z) p
  cross join lateral(select p.paid+case when t.deposit<0 then t.deposit else greatest(0,t.deposit-greatest(p.deposited,0)) end paid) f
  where r.workspace_id=w and r.store='invoices' and r.deleted_at is null and (b->'party' is null or b->'party'='null' or b->'party'->'id'=r.payload->'companyId')
  order by r.payload->>'regDate' desc nulls last,r.record_id limit page_size offset page_start;
 elsif tab='statement' then
  return query with cash as (
   select c.*,case when c.scope in ('finance','wow') or wow_fin.can(ctx,c.scope||'.view') then c.detail else '{}'::jsonb end visible
   from wow_fin.cash c where c.workspace=w and (s='finance' or c.scope=s)
    and (b->>'box' is null or c.box=b->>'box') and (b->>'currency' is null or c.currency=b->>'currency') and (end_day is null or c.day<=end_day)
  ), match as (
   select c.* from cash c where (b->'party' is null or b->'party'='null' or c.visible->'party'=b->'party') and (b->>'employee' is null or c.visible->>'employee'=b->>'employee')
  ), lines as (
   select m.currency,start_day as day,'' id,'' box,'openingBalance' kind,'' description,'' reference,sum(m.amount) amount from match m
    where m.day<start_day group by m.currency
   union all select m.currency,m.day,m.entry,m.box,m.kind,coalesce(m.visible->>'description',m.visible->>'note',''),coalesce(m.visible->>'reference',''),m.amount
    from match m where start_day is null or m.day>=start_day
  ), running as (
   select l.*,sum(l.amount) over(partition by l.currency order by l.day nulls last,l.id,l.box rows unbounded preceding) balance from lines l
  ) select jsonb_build_object('id',r.id,'day',r.day,'kind',r.kind,'description',r.description,'reference',r.reference,'box',r.box,'currency',r.currency,
    'inflow',case when r.kind<>'openingBalance' then greatest(0,r.amount)::text end,'outflow',case when r.kind<>'openingBalance' then greatest(0,-r.amount)::text end,'balance',r.balance::text)
    from running r order by r.currency,r.day nulls last,r.id,r.box limit page_size offset page_start;
 elsif tab in ('ledger','reports') then
  return query with filtered as (
   select x.*,case when x.scope in ('finance','wow') or wow_fin.can(ctx,x.scope||'.view') then x.detail else '{}'::jsonb end visible
   from (select c.* from wow_fin.cash c where c.workspace=w union all
    select j.workspace,j.id::text,j.scope,j.kind,j.day,null::text,null::text,null::numeric,j.detail||jsonb_build_object('grams',j.grams::text,'metal',j.metal),j.reversed_entry::text
    from wow_fin.journal j where j.workspace=w and s='metals' and j.scope='metals' and not exists(select from wow_fin.legs l where l.workspace=w and l.entry=j.id)
   ) x where x.workspace=w and (s='finance' or x.scope=s)
   and (start_day is null or x.day>=start_day) and (end_day is null or x.day<=end_day)
   and (b->>'box' is null or x.box=b->>'box') and (b->>'currency' is null or x.currency=b->>'currency') and (coalesce(b->>'kind','')='' or x.kind=b->>'kind')
  ), matching as (
   select f.* from filtered f where (b->>'category' is null or f.visible->>'category'=b->>'category') and
   (b->'party' is null or b->'party'='null' or f.visible->'party'=b->'party') and (b->>'employee' is null or f.visible->>'employee'=b->>'employee')
   and (b->>'metal' is null or f.visible->>'metal'=b->>'metal') and position(lower(coalesce(b->>'search','')) in lower(f.visible::text||' '||f.entry))>0
  ), result as (
   select f.day sort_day,f.entry sort_id,f.box sort_box,(f.visible||jsonb_build_object('id',f.entry,'scope',f.scope,'kind',f.kind,'day',f.day,'box',f.box,'currency',f.currency,
    'amount',f.amount::text,'reversed',f.reversed_entry is not null or exists(select from wow_fin.journal j where j.workspace=w and j.reversed_entry::text=f.entry))) item from matching f where tab='ledger'
   union all select date_trunc('month',f.day)::date,'',f.box,jsonb_build_object('month',to_char(f.day,'YYYY-MM'),'box',f.box,'currency',f.currency,
    'category',f.visible->>'category','kind',f.kind,'inflow',coalesce(sum(f.amount) filter(where f.amount>0),0)::text,
    'outflow',coalesce(-sum(f.amount) filter(where f.amount<0),0)::text,'net',sum(f.amount)::text,'count',count(*))
   from matching f where tab='reports' group by date_trunc('month',f.day)::date,to_char(f.day,'YYYY-MM'),f.box,f.currency,f.visible->>'category',f.kind
  ) select result.item from result order by sort_day desc nulls last,sort_id,sort_box,item::text limit page_size offset page_start;
 elsif tab in ('quotes','fx') then
  return query select jsonb_build_object('id',q.id,'base',q.base,'counter',q.counter,'rate',q.rate::text,'at',q.observed,'source',q.source,
    'method',q.method,'unit',q.unit,'raw',q.raw::text,'stale',q.observed<now()-interval '3 days')
   from wow_fin.quotes q where q.workspace=w and (s='metals' and tab<>'fx')=(q.base in ('gold','silver')) and (b->>'base' is null or q.base=b->>'base')
   and (b->>'currency' is null or q.counter=b->>'currency') and (start_day is null or q.observed::date>=start_day) and (end_day is null or q.observed::date<=end_day) order by q.observed desc,q.recorded desc,q.id limit page_size offset page_start;
 elsif tab='holdings' then
  return query select jsonb_build_object('metal',m,'grams',coalesce(hold.grams,0)::text,'valuations',coalesce(val.items,'[]'::jsonb))
  from unnest(array['gold','silver']) m cross join lateral (select sum(j.grams) grams from wow_fin.journal j where j.workspace=w and j.metal=m) hold
  cross join lateral(select jsonb_agg(jsonb_build_object('currency',q.counter,'rate',q.rate::text,'value',round(coalesce(hold.grams,0)*q.rate,2)::text,
    'at',q.observed,'source',q.source,'method',q.method,'stale',q.observed<now()-interval '3 days') order by q.counter) items
   from (select distinct on(q.counter) q.* from wow_fin.quotes q where q.workspace=w and q.base=m order by q.counter,q.observed desc,q.recorded desc,q.id) q) val order by m limit page_size offset page_start;
 elsif tab='attendance' then
  return query select a.entry||jsonb_build_object('id',a.id,'version',a.version,'name',r.profile->>'name') from wow_fin.attendance a join wow_fin.resources r on r.workspace=w and r.kind='employee' and r.id=a.employee
  where a.workspace=w and a.active and (b->>'employee' is null or a.employee=(b->>'employee')::uuid) and (b->>'period' is null or date_trunc('month',a.day)::date=month_day)
  and (start_day is null or a.day>=start_day) and (end_day is null or a.day<=end_day) order by a.day desc,r.profile->>'name',a.id limit page_size offset page_start;
 elsif tab='slips' then
  return query select wow_fin.salary(w,r.id,month_day) from wow_fin.resources r where r.workspace=w and r.kind='employee' and (b->>'employee' is null or r.id=(b->>'employee')::uuid) order by r.profile->>'name',r.id limit page_size offset page_start;
 elsif tab='audit' then
  return query select jsonb_build_object('id',r.id,'action',r.action,'actor',a.name,'at',r.at,'scope',s) from wow_fin.receipts r join public.wow_accounts a on a.id=r.actor
   where r.workspace=w and r.scope=s and (start_day is null or r.at::date>=start_day) and (end_day is null or r.at::date<=end_day) order by r.seq desc limit page_size offset page_start;
 else raise exception using message='INVALID_FINANCE_QUERY';end if;
end $$;

create or replace function public.wow_finance_service(p_action text,p_data jsonb) returns jsonb
language plpgsql security definer set search_path='' as $$
#variable_conflict use_variable
declare
 uid uuid=(p_data->>'userId')::uuid;sid uuid=(p_data->>'sessionId')::uuid;ctx jsonb;w uuid;s text=split_part(p_action,'.',1);
 is_read boolean=p_action like '%.list' or p_action like '%.legacy.detail' or p_action in ('finance.archive','finance.attachment');
 checking boolean=p_action like '%.quote.live.check';act text=replace(p_action,'.live.check','.live');cap text;command uuid=(p_data->>'commandId')::uuid;
 input jsonb=p_data-array['userId','sessionId','commandId'];old wow_fin.receipts;res jsonb;rows jsonb;row jsonb;profile jsonb;current_resource wow_fin.resources;
 cur text;dst text;kind text;kid uuid;entry uuid;rev uuid;d date;val numeric;converted numeric;quote wow_fin.quotes;orig wow_fin.journal;cash text;
 gm numeric;rate numeric;observed timestamptz;source text;unit text;method text;raw_rate numeric;employee uuid;per date;sal jsonb;
 n int;lim int;high bigint;hist wow_fin.legacy_rows;st wow_fin.imports;sz int;fx wow_fin.quotes;att wow_fin.attachments;details jsonb;observation jsonb;count_new int=0;count_existing int=0;scope_cmd text;
begin
 if s not in ('finance','payroll','metals') then raise exception using message='INVALID_FINANCE_ACTION';end if;
 if act in ('finance.archive','finance.restore','finance.restore.stage','finance.attach','finance.attachment') then s=p_data->>'scope';end if;
 if coalesce(s,'') not in ('finance','payroll','metals') and not (s='all' and act in ('finance.archive','finance.restore','finance.restore.stage')) then raise exception using message='INVALID_FINANCE_SCOPE';end if;
 ctx=public.wow_actor(uid,sid,null,not is_read,not is_read);
 w=(ctx->>'workspaceId')::uuid;
 cap=case when is_read then 'view' when act like '%.reverse' or act='payroll.remove' then 'delete' else 'edit' end;
 if not wow_fin.can(ctx,s||'.'||cap) then raise exception using message='ACCESS_DENIED';end if;
 if (act in ('finance.archive','finance.restore','finance.restore.stage','metals.opening') or act like '%.legacy.%') and ctx->'account'->>'role'<>'owner' then raise exception using message='ACCESS_DENIED';end if;
 if act='finance.restore.stage' then
  if p_data->>'workspace'<>w::text then raise exception using message='INVALID_ARCHIVE_WORKSPACE';end if;
  kid=(p_data->>'stage')::uuid;n=(p_data->>'start')::int;lim=jsonb_array_length(p_data->'commands');sz=octet_length((p_data->'commands')::text);
  if n<0 or lim not between 1 and 400 or sz>8388608 then raise exception using message='INVALID_ARCHIVE_CHUNK';end if;
  delete from wow_fin.imports i where i.workspace=w and i.expires<now();
  select * into st from wow_fin.imports i where i.workspace=w and i.id=kid;
  if st.id is null then
   if n<>0 or (select count(*) from wow_fin.imports i where i.workspace=w)>=4 then raise exception using message='INVALID_ARCHIVE_STAGE';end if;
   insert into wow_fin.imports(workspace,id,actor,scope,total) values(w,kid,uid,s,(p_data->>'total')::int) returning * into st;
  end if;
  if st.actor<>uid or st.scope<>s or st.total<>(p_data->>'total')::int then raise exception using message='INVALID_ARCHIVE_STAGE';end if;
  if n<st.received then
   if not exists(select from wow_fin.import_chunks c where c.workspace=w and c.stage=kid and c.start_index=n and c.commands=p_data->'commands') then raise exception using message='IDEMPOTENCY_MISMATCH';end if;
  else
   if n<>st.received or n+lim>st.total or st.bytes+sz>134217728 then raise exception using message='INVALID_ARCHIVE_CHUNK';end if;
   insert into wow_fin.import_chunks values(w,kid,n,p_data->'commands');
   update wow_fin.imports set received=n+lim,bytes=bytes+sz where workspace=w and id=kid;
  end if;
  return jsonb_build_object('stage',kid,'next',n+lim);
 end if;
 if act='finance.archive' then
  select coalesce((p_data->>'until')::bigint,max(seq),0) into high from wow_fin.receipts where workspace=w and (scope=s or s='all');
  select coalesce(jsonb_agg(jsonb_build_object('seq',r.seq,'action',r.action,'data',r.request||jsonb_build_object('commandId',r.id)) order by r.seq),'[]') into rows
  from (select p.*,row_number() over(order by p.seq) n,sum(octet_length(p.request::text)) over(order by p.seq) bytes from (
    select * from wow_fin.receipts where workspace=w and (scope=s or s='all') and action<>'finance.restore' and seq>coalesce((p_data->>'after')::bigint,0) and seq<=high
     order by seq limit greatest(1,least(100,coalesce((p_data->>'limit')::int,40)))) p) r where r.n=1 or r.bytes<=7340032;
  return jsonb_build_object('workspace',w,'scope',s,'until',high,'commands',rows);
 elsif act like '%.legacy.detail' then
  select * into hist from wow_fin.legacy_rows h where h.workspace=w and h.scope=s and h.id=(p_data->>'id')::uuid;
  if hist.id is null then raise exception using message='ACCESS_DENIED';end if;return jsonb_build_object('record',hist.record);
 elsif act='finance.attachment' then
  select * into att from wow_fin.attachments a where a.workspace=w and a.id=(p_data->>'id')::uuid and a.scope=s;
  if att.id is null then raise exception using message='ACCESS_DENIED';end if;
  return jsonb_build_object('file',jsonb_build_object('name',att.name,'mime',att.mime,'data',replace(encode(att.bytes,'base64'),E'\n','')));
 elsif act like '%.list' then
  if (p_data->>'tab') not in (select unnest(case s when 'finance' then array['boxes','resources','customers','invoices','ledger','reports','quotes','statement','barcodes','audit','legacy']
    when 'payroll' then array['boxes','resources','attendance','slips','ledger','statement','audit','legacy'] else array['boxes','ledger','quotes','fx','holdings','audit','legacy'] end)) then raise exception using message='ACCESS_DENIED';end if;
  lim=greatest(1,least(200,coalesce((p_data->>'limit')::int,50)));
  select coalesce(jsonb_agg(v),'[]') into rows from (select v from wow_fin.query_rows(w,ctx,s,p_data) v) q;
  return jsonb_build_object('items',case when jsonb_array_length(rows)>lim then rows-lim else rows end,'more',jsonb_array_length(rows)>lim);
 end if;
 if command is null then raise exception using message='INVALID_COMMAND_ID';end if;
 select * into old from wow_fin.receipts r where r.workspace=w and r.id=command;
 if old.id is not null then
